	sep #$20
	lda.b #INIDISP_FBLANK|$0F
	sta.w INIDISP
	stz.w OBSEL
	stz.w OAMADDL
	stz.w OAMADDH
	stz.w BGMODE
	stz.w MOSAIC
	stz.w BG1SC
	stz.w BG2SC
	stz.w BG3SC
	stz.w BG4SC
	stz.w BG12NBA
	stz.w BG34NBA
	stz.w BG1HOFS
	stz.w BG1HOFS
	stz.w BG1VOFS
	stz.w BG1VOFS
	stz.w BG2HOFS
	stz.w BG2HOFS
	stz.w BG2VOFS
	stz.w BG2VOFS
	stz.w BG3HOFS
	stz.w BG3HOFS
	stz.w BG3VOFS
	stz.w BG3VOFS
	stz.w BG4HOFS
	stz.w BG4HOFS
	stz.w BG4VOFS
	stz.w BG4VOFS
	lda.b #VMAIN_INCHI
	sta.w VMAIN
	stz.w VMADDL
	stz.w VMADDH
	stz.w M7SEL
	stz.w M7A
	lda.b #$01
	sta.w M7A
	stz.w M7B
	stz.w M7B
	stz.w M7C
	stz.w M7C
	stz.w M7D
	sta.w M7D
	stz.w M7X
	stz.w M7X
	stz.w M7Y
	stz.w M7Y
	stz.w CGADD
	stz.w W12SEL
	stz.w W34SEL
	stz.w WOBJSEL
	stz.w WH0
	stz.w WH1
	stz.w WH2
	stz.w WH3
	stz.w WBGLOG
	stz.w WOBJLOG
	stz.w TM
	stz.w TS
	stz.w TMW
	stz.w TSW
	lda.b #$30
	sta.w CGWSEL
	stz.w CGADSUB
	lda.b #$E0
	sta.w COLDATA
	stz.w SETINI
	stz.w NMITIMEN
	lda.b #$FF
	sta.w WRIO
	stz.w WRMPYA
	stz.w WRMPYB
	stz.w WRDIVL
	stz.w WRDIVH
	stz.w WRDIVB
	stz.w HTIMEL
	stz.w HTIMEH
	stz.w VTIMEL
	stz.w VTIMEH
	stz.w MDMAEN
	stz.w HDMAEN
	lda.b #$01
	sta.w MEMSEL
	rep #$30
	rtl
